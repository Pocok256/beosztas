const fs = require("node:fs");
const path = require("node:path");
const pug = require("pug");

const templatesDir = path.join(process.cwd(), "src", "features", "schedule-ui", "internal", "templates");
const outputFile = path.join(process.cwd(), "src", "features", "schedule-ui", "internal", "CompiledTemplates.ts");

function toExportName(fileName) {
  const baseName = path.basename(fileName, ".pug");
  return `${baseName[0].toLowerCase()}${baseName.slice(1)}Template`;
}

const files = fs
  .readdirSync(templatesDir)
  .filter((fileName) => fileName.endsWith(".pug"))
  .sort();

const sections = files.map((fileName) => {
  const templatePath = path.join(templatesDir, fileName);
  const functionSource = pug.compileFileClient(templatePath, {
    compileDebug: false,
    name: "template"
  });
  const exportName = toExportName(fileName);

  return `export const ${exportName}: PugTemplate = (() => {\n${functionSource}\nreturn template;\n})();`;
});

const output = `// This file is generated by scripts/compileClientPugTemplates.js.\n// @ts-nocheck\n\ntype PugTemplate = (locals?: Record<string, unknown>) => string;\n\n${sections.join("\n\n")}\n`;

fs.writeFileSync(outputFile, output);
